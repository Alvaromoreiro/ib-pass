import { merge, cloneDeep } from 'lodash-es';
import { IbBookingAvailabilityUtilsService } from '../../../../shared/services/ib-booking-availability/ib-booking-availability-utils-service';
import { getFareTitleTranslation } from './availability-fare-title-literal';
import { IbOriginDestinationInfoUtilsService } from './ib-origin-destination-info-utils-service';
@Service('ib-booking-availability-module',
    ['IbOriginDestinationInfoUtilsService', 'CurrencyService', 'IbBookingAvailabilityUtilsService', '$filter', 'BookingAvailabilityConstants',
        'BookingAppConstants', 'BookingUtilService', 'localStorageService'])
export class IbOriginDestinationInfoService {
    constructor (
        private IbOriginDestinationInfoUtilsService: IbOriginDestinationInfoUtilsService,
        private CurrencyService: CurrencyService,
        private IbBookingAvailabilityUtilsService: IbBookingAvailabilityUtilsService,
        private $filter: ng.FilterFactory,
        private BookingAvailabilityConstants: any,
        private BookingAppConstants: BookingAppConstants,
        private BookingUtilService: any,
        private localStorageService: angular.local.storage.ILocalStorageService
    ) {
    }

    /**
     * Creates the originDestinations object to show in the view. Builds an array de slices with the possible offers for the slice.
     * @param {AvailabilityTransformerModel.OffersGeneratorResponse} offersInfo - An object with the needed offer information. Generated by the "generateOfferParams" method.
     * @param {AvailabilityTransformerModel.OptionsGeneratorResponse} options - Miscellaneous information still needed to fabricate the "OriginDestination" object. Generated by the "generateOptionParams" method.
 
     * @returns {AvailabilityTransformerModel.OriginDestination} - returns the originDestination object with its associated slices and offers
     */

    create = (offersInfo: AvailabilityTransformerModel.OffersGeneratorResponse, options: AvailabilityTransformerModel.OptionsGeneratorResponse): AvailabilityTransformerModel.OriginDestination  => {
        let { slicePricesByCabin, slicePrices, bestPrice, isAvailable, originCurrencyCode } = this.IbOriginDestinationInfoUtilsService.initializeDefaultValues();
        let { originDestination, offers, fareFamilyConditions, currentOffers } = offersInfo;
        let { calendar, currencies } = options;

        originDestination.slices.forEach((slice, index)=> {
            let maxSlicePrice = 0;
            const sliceOffers: AvailabilityTransformerModel.Offer[] = this.getSliceOffers(originDestination.originDestinationId, slice, offers);

            const sliceOffersByFareFamilies: AvailabilityTransformerModel.SliceOffersByFareFamilies = this.getSliceOffersByFareFamilies(
                originDestination.originDestinationId, slice.sliceId, sliceOffers, fareFamilyConditions, currentOffers, currencies);

            isAvailable = sliceOffersByFareFamilies.fareFamilies.slicePrice !== 0;
            originCurrencyCode = sliceOffersByFareFamilies.fareFamilies.sliceCurrency;

            slice.cabins = sliceOffersByFareFamilies.cabins; 
            slice.cabinsLength = sliceOffersByFareFamilies.cabinsLength;
            slice.cabinsMobile = sliceOffersByFareFamilies.cabinsMobile;
            slice.cabinsMobileLength = sliceOffersByFareFamilies.cabinsMobileLength;

            this.IbOriginDestinationInfoUtilsService.assignSliceDefaults(slice);

            this.IbOriginDestinationInfoUtilsService.assignSlicePrices(slice, sliceOffersByFareFamilies, currencies);

            this.IbOriginDestinationInfoUtilsService.assignSliceDates(slice);

            this.handleSliceSegments(slice);

            const arrayBestPrices: AvailabilityTransformerModel.PricesByCabin  = this.IbOriginDestinationInfoUtilsService.getSlicePriceByCabin(sliceOffersByFareFamilies);
            Object.keys(arrayBestPrices).forEach((cabinType) => {
                if(!slicePricesByCabin[cabinType]) {
                    slicePricesByCabin[cabinType] = [];
                }
                slicePricesByCabin[cabinType].push(arrayBestPrices[cabinType]);
                maxSlicePrice = maxSlicePrice > 0 ? Math.max(maxSlicePrice, arrayBestPrices[cabinType]) : arrayBestPrices[cabinType];
            });
            slicePrices.push(slice.slicePrice);
            bestPrice = bestPrice > 0 ?
                Math.min(bestPrice, sliceOffersByFareFamilies.fareFamilies.slicePrice)
                : sliceOffersByFareFamilies.fareFamilies.slicePrice;
            slice.maxSlicePrice = maxSlicePrice;
            slice.sliceSelectedDiscount = this.sliceSpecialDiscount( slice.cabins );
            slice.sliceSelectedDiscountImage = slice.sliceSelectedDiscount ? this.getSliceSelectDiscountImageType( slice.sliceSelectedDiscount ) : null;
            slice.slicePromotionImage = slice.sliceSelectedDiscountImage ? this.getSliceSelectDiscountImagePath( slice.sliceSelectedDiscountImage ) : null;
        });

        originDestination.selectedFilters = null;
        originDestination.loadingAvailability = false;

        originDestination.slices = this.IbOriginDestinationInfoUtilsService.checkBestPriceandAvailabilitySlice(originDestination.slices, bestPrice);
        let cabins = cloneDeep(  originDestination.slices[originDestination.slices.length-1].cabins);
        originDestination.currency = originCurrencyCode;
        if (calendar) {
            originDestination.calendarSlides = this.IbOriginDestinationInfoUtilsService.getSlidesData(
                calendar,
                currencies[originCurrencyCode]);
            originDestination.calendarSlides.currency = currencies[originCurrencyCode];
        } else {
            originDestination.calendarSlides = null;
        }
        originDestination.isAvailable = isAvailable;
        originDestination.filterOptions = this.IbOriginDestinationInfoUtilsService.getFilterOptions(
            cabins,
            currencies[originCurrencyCode],
            slicePricesByCabin);
        originDestination.initialFilterOptions = cloneDeep(originDestination.filterOptions);


        return originDestination;

    };

    private handleSliceSegments = (slice:  AvailabilityTransformerModel.Slice) => {
        slice.segments.forEach( (segment, index) => {
            const logoURLS = this.BookingUtilService.getCompanyURL(segment.flight.operationalDisclosure);
            segment.durationParsed = this.$filter('DurationFormatFilter')(segment.duration);
            segment.isMoreThan2h = this.IbBookingAvailabilityUtilsService.moreThan2Hours(segment.waitingTime);
            segment.waitingTimeParsed = this.$filter('DurationFormatFilter')(segment.waitingTime);
            segment.departureDateTimeParsed = segment.departureDateTime.split(' ')[1];
            segment.departureDateParsed = this.$filter('DateFormatFilter')(segment.departureDateTime);
            segment.arrivalDateParsed = this.$filter('DateFormatFilter')(segment.arrivalDateTime);
            segment.arrivalDateTimeParsed = segment.arrivalDateTime.split(' ')[1];
            segment.companyURL = logoURLS?.logo;
            segment.companyURLMin = logoURLS?.logoMin;
            segment.delayInformation = this.checkAndTransformDelayInfo(segment.delayInformation);
            if(segment.stop) {
                segment.stop = this.IbOriginDestinationInfoUtilsService.getStopInformation(segment);
                slice.technicalStop++;
            }
            if(index===0) {
                slice.sliceURL = segment.companyURL;
                slice.sliceURLMin = segment.companyURLMin;
            }
            if (slice.allOperatedBy.indexOf(segment.flight.operationalCarrier.code) === -1) {
                slice.allOperatedBy.push(segment.flight.operationalCarrier.name);
                slice.allOperatedByCodes.push(segment.flight.operationalCarrier.code);
            }
            merge(segment,
                this.IbBookingAvailabilityUtilsService.generateSegmentWarningMessage(
                    segment,
                    index > 0
                        ? slice.segments[index - 1]
                        : null
                ));
        });
        
    };

    private checkAndTransformDelayInfo (delayInfo: AvailabilityTransformerModel.DelayInformation) {
        if (!delayInfo?.flightNumber) return delayInfo ?? null;
        return this.IbOriginDestinationInfoUtilsService.getDelayInformation(delayInfo);
    }

    private getSliceOffers = (
        originDestinationId: string,
        slice: AvailabilityTransformerModel.Slice,
        currentOffers: AvailabilityTransformerModel.Offer[]
    ): AvailabilityTransformerModel.Offer[] => {
        const selectedOffers = [];
        if (originDestinationId) {
            currentOffers.forEach((offer)=> {
                const founded = [];
                offer.originDestinations.forEach((origin) => {
                    let match = [];
                    if(originDestinationId === origin.originDestinationId) {
                        match = origin.applicableSlices.filter( (sliceOrigin) =>{
                            return sliceOrigin.sliceId === slice.sliceId;
                        });
                    }
                    if(match.length >0) {
                        founded.push(match);
                    }
                });
                if (founded.length >0) {
                    selectedOffers.push(offer);
                }
            });
        }else{
            if (currentOffers.length === 1) {
                selectedOffers.push(currentOffers[0]);
            }
        }

        return selectedOffers;

    };

    private getSliceOffersByFareFamilies = (
        originDestinationId: string,
        sliceId: number,
        currentOffers: AvailabilityTransformerModel.Offer[],
        fareFamilies: AvailabilityTransformerModel.FareFamilyOptions,
        selectedOffersToCheck: AvailabilityTransformerModel.Offer[],
        currencies: AvailabilityTransformerModel.CurrenciesObject
    ): AvailabilityTransformerModel.SliceOffersByFareFamilies => {
        const sliceOffer:AvailabilityTransformerModel.SliceOffersByFareFamilies = {
            fareFamilies: {
                fareFamilies: {},
                slicePrice: 0,
                slicePriceWithoutDiscount: null,
                sliceCurrency: null
            },
            cabins: {},
            cabinsLength: 0,
            cabinsMobile: [],
            cabinsMobileLength: 0
        };
        const selectedFareFamilies: AvailabilityTransformerModel.SliceOffersByFareFamiliesFareFamilies = {
            fareFamilies: {},
            slicePrice: 0,
            slicePriceWithoutDiscount: null,
            sliceCurrency: null
        };
        Object.keys(fareFamilies).forEach( (fare) => {
            const singleFareFamily = this.getFareFamilyOffers(
                originDestinationId, sliceId, currentOffers, fareFamilies[fare],
                selectedOffersToCheck, currencies
            );
            if (singleFareFamily !== null) {
                selectedFareFamilies.slicePrice = selectedFareFamilies.slicePrice > 0
                    ? Math.min(selectedFareFamilies.slicePrice, singleFareFamily.farePriceToCalculate) : singleFareFamily.farePriceToCalculate;
                selectedFareFamilies.slicePriceWithoutDiscount = selectedFareFamilies.slicePriceWithoutDiscount > 0 
                    ? Math.min(selectedFareFamilies.slicePriceWithoutDiscount, singleFareFamily.fareDiscountPriceToCalculate) : singleFareFamily.fareDiscountPriceToCalculate;

                selectedFareFamilies.sliceCurrency = singleFareFamily.fareCurrency;
                selectedFareFamilies.fareFamilies[fareFamilies[fare].commercialCode] = singleFareFamily;
            }
        });

        sliceOffer.fareFamilies = selectedFareFamilies;
        sliceOffer.cabins = this.IbOriginDestinationInfoUtilsService.getSelectedCabins(selectedFareFamilies.fareFamilies, selectedFareFamilies.sliceCurrency, currencies);
        sliceOffer.cabinsMobile = this.IbOriginDestinationInfoUtilsService.getSelectedCabinsMobile(selectedFareFamilies.fareFamilies, sliceOffer.cabins);
        sliceOffer.cabinsLength = Object.keys( sliceOffer.cabins).length;
        sliceOffer.cabinsMobileLength = sliceOffer.cabinsMobile.length;
        return sliceOffer;

    };

    private getFareFamilyOffers = (
        originDestinationId: string,
        sliceId: number,
        sliceOffersData: AvailabilityTransformerModel.Offer[],
        fareFamily: AvailabilityTransformerModel.FareFamilyCondition,
        compatibleOffers: AvailabilityTransformerModel.Offer[],
        currencies: AvailabilityTransformerModel.CurrenciesObject
    ): AvailabilityTransformerModel.FareFamilyCondition => {
        const returnedFareFamily =  cloneDeep(fareFamily);
        const typeFligth = this.localStorageService.get('searchFlightType');
        const fareDetailedInfo: AvailabilityTransformerModel.FareDetailedInfo =
            this.IbOriginDestinationInfoUtilsService.getFarePricesAndOffers(
                originDestinationId, sliceId, sliceOffersData, fareFamily);
        if (compatibleOffers && compatibleOffers.length > 0) {
            const data = this.IbOriginDestinationInfoUtilsService.upgradeFarePrice(originDestinationId, fareDetailedInfo, compatibleOffers);
            fareDetailedInfo.farePrice = data.price;
            fareDetailedInfo.includedPriceDiscount = data.includedPriceDiscount;
            if (data.discount !== null) {
                fareDetailedInfo.fareDiscountPrice = data.discount;
            }
        }

        returnedFareFamily.isCompatibleFare = compatibleOffers && compatibleOffers.length > 0 ?
            this.IbBookingAvailabilityUtilsService.isFareCompatible(fareDetailedInfo.offers, compatibleOffers) : true;
        returnedFareFamily.farePrice = fareDetailedInfo.bestFarePrice;
        returnedFareFamily.fareDiscountPriceToCalculate = fareDetailedInfo.fareDiscountPrice ?
            fareDetailedInfo.fareDiscountPrice : 0;
        returnedFareFamily.farePriceToCalculate = fareDetailedInfo.farePrice;
        returnedFareFamily.farePriceShown = this.CurrencyService.formatPrice(
            currencies[fareDetailedInfo.currency], fareDetailedInfo.farePrice, false, true);
        returnedFareFamily.fareOutTax = fareDetailedInfo.fareOutTax;
        returnedFareFamily.fareDiscountPriceShown = fareDetailedInfo.fareDiscountPrice
            ? this.CurrencyService.formatPrice(
                currencies[fareDetailedInfo.currency], fareDetailedInfo.fareDiscountPrice, false, true)
            : null;
        returnedFareFamily.fareCurrency = fareDetailedInfo.currency;
        returnedFareFamily.remainingSeats = fareDetailedInfo.remainingSeats;
        returnedFareFamily.offers = fareDetailedInfo.offers;
        returnedFareFamily.oBdiscount = fareDetailedInfo.oBdiscount;
        returnedFareFamily.includedPriceDiscount = fareDetailedInfo.includedPriceDiscount;
        returnedFareFamily.fareText = getFareTitleTranslation(returnedFareFamily);
        let result = null;
        if(this.BookingAppConstants.AVAILABLE_REFACTOR && typeFligth !== this.BookingAppConstants.SEARCH_FLIGHT_TYPE.MULTITRIP) {
            if(returnedFareFamily.offers.length > 0 && returnedFareFamily.isCompatibleFare) {
                result = returnedFareFamily;
            }
        } else{
            if(returnedFareFamily.offers.length > 0) {
                result = returnedFareFamily;
            }
        }
        return result;

    };



    sliceSpecialDiscount = ( cabins ): AvailabilityTransformerModel.SliceSelectedDiscount => {
        const sliceOffersDiscounts = [];
        Object.values( cabins ).forEach( ( cabin: any ) => {
            cabin?.fareFamilies?.forEach( fareFamily => {
                fareFamily?.offers?.forEach( offer => {
                    if ( offer?.specialDiscountsApplied ) sliceOffersDiscounts.push( offer.specialDiscountsApplied.find( this.checkSliceDiscountType ) );
                });
            });
        });
        const selectedDiscount = sliceOffersDiscounts.find( this.checkSliceDiscountType );
        return selectedDiscount ? selectedDiscount : false;
    };
    checkSliceDiscountType = (discount) => {
        return discount?.type === this.BookingAppConstants.DISCOUNT_TYPES.PARTNER || discount?.type === this.BookingAppConstants.DISCOUNT_TYPES.CORPORATE;
    };
    getSliceSelectDiscountImageType = ( discount ) => {
        if ( discount.type === this.BookingAppConstants.DISCOUNT_TYPES.CORPORATE ) {
            return this.BookingAppConstants.SLICE_CORPORATE_ICON_MAP[ discount.corporateCodes ?? 'default' ]?.imageSuffix ?? this.BookingAppConstants.SLICE_CORPORATE_ICON_MAP[ 'default' ].imageSuffix;
        }
        if ( discount.type === this.BookingAppConstants.DISCOUNT_TYPES.PARTNER ) {
            return discount?.partner?.partnerId?.includes( this.BookingAppConstants.CAMPAING_TYPE ) ? 'campaign' : discount?.partner?.partnerId?.toLowerCase();
        }
    };
    
    getSliceSelectDiscountImagePath = ( image: string ) => {
        return `${ this.BookingAppConstants.iconsRoute }/partners/partners-logo-${ image }.svg`;
    };

    generateOfferParams = (originDestinations: AvailabilityTransformerModel.OriginDestination, offers: AvailabilityTransformerModel.Offer[], fareFamilies: AvailabilityTransformerModel.FareFamilyOptions, currentOffers?: AvailabilityTransformerModel.Offer[]): AvailabilityTransformerModel.OffersGeneratorResponse => {
        return {
            originDestination: originDestinations,
            offers: offers,
            fareFamilyConditions: fareFamilies,
            currentOffers: currentOffers ?? []
        };
    };

    generateOptionParams = (currencies: AvailabilityTransformerModel.CurrenciesObject, calendarInfo?: AvailabilityTransformerModel.CalendarData | null, index?: number): AvailabilityTransformerModel.OptionsGeneratorResponse => {
        return {
            currencies: currencies,
            calendar: calendarInfo ?? null,
            index: index ?? null
        };
    };
}
