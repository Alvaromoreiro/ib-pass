export const getFareTitleTranslation = (
    fareInfo: AvailabilityTransformerModel.FareFamilyCondition
): string => {
    const commercialName = normalizedKebabCase(fareInfo.commercialNameES);
    const cabinType = fareInfo.cabinType;

    return (
        translationMap[cabinType]?.[commercialName] ??
        DEFAULT_TRANSLATION
    );
};
